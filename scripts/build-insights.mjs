// build-insights.mjs: writes one finished HTML page per published article into insights/<slug>.html.
// Run after editing js/insights.js:   node scripts/build-insights.mjs
// The pages are committed, so Amplify still serves plain files with no build step, and link previews
// (LinkedIn, WhatsApp, Slack) and search engines see the real title, description, image and text.

import { readFileSync, writeFileSync, readdirSync, unlinkSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

process.env.TZ = "Europe/London";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { published, categoryLabel, esc } = await import(join(root, "js/insights.js"));
const { articleHTML, headMeta, ldJSON, SITE } = await import(join(root, "js/article-render.js"));

const template = readFileSync(join(root, "insights/article.html"), "utf8");
const MARK = "<!-- Generated by scripts/build-insights.mjs from js/insights.js. Edit those, not this file. -->";

// Remove pages for articles that are no longer published.
const live = new Set(published().map(a => `${a.slug}.html`));
for (const f of readdirSync(join(root, "insights"))) {
  if (f.endsWith(".html") && !live.has(f) && readFileSync(join(root, "insights", f), "utf8").startsWith(MARK)) {
    unlinkSync(join(root, "insights", f)); console.log("removed insights/" + f);
  }
}

const urls = [];
for (const a of published()) {
  const m = headMeta(a);
  const head = `<title>${esc(m.title)}</title>
  <meta name="description" content="${esc(m.desc)}">
  <link rel="canonical" href="${m.url}">
  <meta property="og:site_name" content="Gibson Nyendwa">
  <meta property="og:locale" content="en_GB">
  <meta property="og:title" content="${esc(m.ogTitle)}">
  <meta property="og:description" content="${esc(m.ogDesc)}">
  <meta property="og:url" content="${m.url}">
  <meta property="og:image" content="${m.image}">
  <meta property="og:type" content="article">
  <meta property="article:published_time" content="${esc(a.published)}">${a.updated ? `\n  <meta property="article:modified_time" content="${esc(a.updated)}">` : ""}
  <meta name="twitter:card" content="summary_large_image">
  <script type="application/ld+json">${JSON.stringify(ldJSON(a)).replace(/</g, "\\u003c")}</script>`;

  const html = template
    .replace(/<title>[\s\S]*?<meta property="og:type"[^>]*>/, head)
    .replace(/<span id="crumb-cat"><\/span>/, `<span id="crumb-cat"><a href="index.html?category=${esc(a.category)}">${esc(categoryLabel(a.category))}</a></span>`)
    .replace(/<article id="article">[\s\S]*?<\/article>\s*<noscript>[\s\S]*?<\/noscript>/, `<article id="article" data-slug="${esc(a.slug)}">${articleHTML(a)}\n  </article>`)
    .replace('<script type="module" src="../js/article.js"></script>', '<script type="module" src="../js/article-wire.js"></script>');

  if (html.includes('name="robots" content="noindex"') || !html.includes("article-wire.js")) throw new Error("Template changed: check insights/article.html");
  writeFileSync(join(root, "insights", `${a.slug}.html`), MARK + "\n" + html);
  urls.push({ url: m.url, lastmod: a.updated || a.published });
  console.log("wrote insights/" + a.slug + ".html");
}

// Keep the sitemap's article entries in step.
const smPath = join(root, "sitemap.xml");
let sm = readFileSync(smPath, "utf8")
  .replace(/\s*<url><loc>[^<]*\/insights\/(article\.html\?slug=[^<]*|[a-z0-9-]+\.html)<\/loc>(<lastmod>[^<]*<\/lastmod>)?<\/url>/g, "");
sm = sm.replace("</urlset>", urls.map(u => `  <url><loc>${u.url}</loc><lastmod>${u.lastmod}</lastmod></url>`).join("\n") + "\n</urlset>");
writeFileSync(smPath, sm);
console.log(`sitemap updated (${SITE})`);
