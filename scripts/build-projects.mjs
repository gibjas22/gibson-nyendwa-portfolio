// build-projects.mjs: writes one finished HTML page per project into projects/<id>.html.
// Run after editing js/projects.js:   node scripts/build-projects.mjs
// The pages are committed, so Amplify still serves plain files with no build step.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { projects } = await import(join(root, "js/projects.js"));
const { caseHTML, esc } = await import(join(root, "js/case-render.js"));

const SITE = "https://main.dbthjbi29n1oo.amplifyapp.com";
const template = readFileSync(join(root, "project.html"), "utf8");

// Every relative URL in the page gains ../ because the pages live one folder down.
const rebase = html => html
  .replace(/\b(href|src)="(?!https?:|mailto:|#|\/|data:|\.\.\/)([^"]+)"/g, (m, a, u) => `${a}="../${u}"`)
  .replace(/\bsrcset="([^"]+)"/g, (m, set) => `srcset="${set.split(",").map(part => {
    const t = part.trim(); return /^(https?:|\/)/.test(t) ? t : "../" + t;
  }).join(", ")}"`);

mkdirSync(join(root, "projects"), { recursive: true });
const urls = [];
for (const p of projects) {
  const url = `${SITE}/projects/${p.id}.html`;
  const shot = (p.shots || [])[0];
  const image = shot ? `${SITE}/${shot.src}` : `${SITE}/assets/img/gibson-600.jpg`;
  const title = `${p.title}: a case study by Gibson Nyendwa`;
  const head = `<title>${esc(title)}</title>
  <meta name="description" content="${esc(p.summary)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="article">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(p.summary)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${image}">
  <meta name="twitter:card" content="summary_large_image">`;
  let html = template
    .replace(/<title>[\s\S]*?<meta name="description"[^>]*>/, head)
    .replace(/<article id="case-body">[\s\S]*?<\/article>\s*<noscript>[\s\S]*?<\/noscript>/,
      `<article id="case-body" data-id="${p.id}">${caseHTML(p)}\n  </article>`)
    .replace('<p class="crumbs"><a href="index.html#projects">All projects</a></p>\n  <article', '<p class="crumbs"><a href="index.html#projects">All projects</a></p>\n  <article')
    .replace('<script type="module" src="js/project.js"></script>', '<script type="module" src="js/case.js"></script>');
  html = "<!-- Generated by scripts/build-projects.mjs from js/projects.js. Edit those, not this file. -->\n" + rebase(html);
  writeFileSync(join(root, "projects", `${p.id}.html`), html);
  urls.push(url);
  console.log("wrote projects/" + p.id + ".html");
}

// Keep the sitemap's project entries in step.
const smPath = join(root, "sitemap.xml");
let sm = readFileSync(smPath, "utf8").replace(/\s*<url><loc>[^<]*(project\.html\?id=|\/projects\/)[^<]*<\/loc>(<lastmod>[^<]*<\/lastmod>)?<\/url>/g, "");
const today = new Date().toISOString().slice(0, 10);
sm = sm.replace("</urlset>", urls.map(u => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join("\n") + "\n</urlset>");
writeFileSync(smPath, sm);
console.log("sitemap updated");
